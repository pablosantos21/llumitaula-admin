test("downloadXlsxBytes executes browser DOM download workflow when document is available", () => {
  const bytes = new Uint8Array([1, 2, 3, 4]);
  let clicked = false;
  let appended = false;
  let removed = false;
  let revokedUrl = null;
  let createdBlob = null;
  const anchorProps = {};

  const originalWindow = globalThis.window;
  const originalDocument = globalThis.document;
  const originalBlob = globalThis.Blob;
  const originalUrl = globalThis.URL;

  try {
    globalThis.Blob = class MockBlob {
      constructor(parts, options) {
        this.parts = parts;
        this.type = options?.type;
        createdBlob = this;
      }
    };

    globalThis.URL = {
      createObjectURL: (blob) => `blob:mock-${blob.type}`,
      revokeObjectURL: (url) => {
        revokedUrl = url;
      },
    };

    const mockAnchor = {
      set href(val) {
        anchorProps.href = val;
      },
      get href() {
        return anchorProps.href;
      },
      set download(val) {
        anchorProps.download = val;
      },
      get download() {
        return anchorProps.download;
      },
      click() {
        clicked = true;
      },
      remove() {
        removed = true;
      },
    };

    globalThis.document = {
      createElement: (tag) => {
        if (tag === "a") return mockAnchor;
        throw new Error(`Unexpected tag: ${tag}`);
      },
      body: {
        appendChild: (el) => {
          if (el === mockAnchor) appended = true;
        },
      },
    };

    downloadXlsxBytes(bytes, "test-download.xlsx");

    assert.ok(createdBlob !== null, "Blob must be constructed");
    assert.equal(
      createdBlob.type,
      "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet"
    );
    assert.equal(anchorProps.download, "test-download.xlsx");
    assert.equal(
      anchorProps.href,
      "blob:mock-application/vnd.openxmlformats-officedocument.spreadsheetml.sheet"
    );
    assert.ok(appended, "Anchor must be appended to document.body");
    assert.ok(clicked, "Anchor must be clicked");
    assert.ok(removed, "Anchor must be removed");
    assert.equal(
      revokedUrl,
      "blob:mock-application/vnd.openxmlformats-officedocument.spreadsheetml.sheet"
    );
  } finally {
    globalThis.window = originalWindow;
    globalThis.document = originalDocument;
    globalThis.Blob = originalBlob;
    globalThis.URL = originalUrl;
  }
});

