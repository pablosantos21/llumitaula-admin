import assert from "node:assert/strict";
import test from "node:test";
import { read, utils } from "xlsx";
import { aoaToXlsxBytes, downloadXlsxBytes } from "../src/lib/xlsx-download.ts";
import { tableFromBytes } from "../src/lib/child-import-xlsx.ts";
import { mapSupabaseUser } from "../src/services/auth.service.ts";

test("aoaToXlsxBytes generates a valid Uint8Array instance", () => {
  const table = [
    ["Nombre", "Apellidos", "Aula"],
    ["Lucía", "Fernández", "Aula 1"],
  ];
  const bytes = aoaToXlsxBytes(table);
  assert.ok(bytes instanceof Uint8Array, "Result must be an instance of Uint8Array");
  assert.ok(bytes.length > 0, "Generated bytes must not be empty");
});

test("aoaToXlsxBytes round-trips data accurately using tableFromBytes", () => {
  const table = [
    ["nombre", "apellidos", "aula"],
    ["Carlos", "Santana", "Primaria A"],
    ["María José", "García López", "Infantil B"],
  ];
  const bytes = aoaToXlsxBytes(table, "Alumnos");
  const parsed = tableFromBytes(bytes);

  assert.ok(parsed !== null, "Parsed table must not be null");
  assert.equal(parsed.length, 3);
  assert.deepEqual(parsed[0], ["nombre", "apellidos", "aula"]);
  assert.deepEqual(parsed[1], ["Carlos", "Santana", "Primaria A"]);
  assert.deepEqual(parsed[2], ["María José", "García López", "Infantil B"]);
});

test("aoaToXlsxBytes respects custom sheetName and column widths", () => {
  const table = [
    ["ID", "Descripcion", "Estado"],
    [101, "Test description", "Activo"],
  ];
  const customSheet = "ReportePersonalizado";
  const colWidths = [{ wch: 10 }, { wch: 30 }, { wch: 15 }];

  const bytes = aoaToXlsxBytes(table, customSheet, colWidths);
  const workbook = read(bytes, { type: "array", cellStyles: true });

  assert.deepEqual(workbook.SheetNames, [customSheet]);
  const sheet = workbook.Sheets[customSheet];
  assert.ok(sheet, "Custom sheet must exist in workbook");
  assert.deepEqual(
    sheet["!cols"]?.map((c) => c.wch),
    [10, 30, 15]
  );

  const json = utils.sheet_to_json(sheet, { header: 1 });
  assert.deepEqual(json, table);
});

test("aoaToXlsxBytes defaults sheetName to 'Sheet1' when omitted", () => {
  const table = [["Header1", "Header2"]];
  const bytes = aoaToXlsxBytes(table);
  const workbook = read(bytes, { type: "array" });

  assert.deepEqual(workbook.SheetNames, ["Sheet1"]);
});

test("downloadXlsxBytes is an exported function accepting bytes and filename", () => {
  assert.equal(typeof downloadXlsxBytes, "function");
  assert.equal(downloadXlsxBytes.length, 2);
});

test("downloadXlsxBytes executes browser DOM download workflow when document is available", () => {
  const bytes = new Uint8Array([1, 2, 3, 4]);
  let clicked = false;
  let appended = false;
  let removed = false;
  let revokedUrl = null;
  let createdBlob = null;
  const anchorProps = {};

  const originalWindow = globalThis.window;
  const originalDocument = globalThis.document;
  const originalBlob = globalThis.Blob;
  const originalUrl = globalThis.URL;

  try {
    globalThis.Blob = class MockBlob {
      constructor(parts, options) {
        this.parts = parts;
        this.type = options?.type;
        createdBlob = this;
      }
    };

    globalThis.URL = {
      createObjectURL: (blob) => `blob:mock-${blob.type}`,
      revokeObjectURL: (url) => {
        revokedUrl = url;
      },
    };

    const mockAnchor = {
      set href(val) {
        anchorProps.href = val;
      },
      get href() {
        return anchorProps.href;
      },
      set download(val) {
        anchorProps.download = val;
      },
      get download() {
        return anchorProps.download;
      },
      click() {
        clicked = true;
      },
      remove() {
        removed = true;
      },
    };

    globalThis.document = {
      createElement: (tag) => {
        if (tag === "a") return mockAnchor;
        throw new Error(`Unexpected tag: ${tag}`);
      },
      body: {
        appendChild: (el) => {
          if (el === mockAnchor) appended = true;
        },
      },
    };

    downloadXlsxBytes(bytes, "test-download.xlsx");

    assert.ok(createdBlob !== null, "Blob must be constructed");
    assert.equal(
      createdBlob.type,
      "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet"
    );
    assert.equal(anchorProps.download, "test-download.xlsx");
    assert.equal(
      anchorProps.href,
      "blob:mock-application/vnd.openxmlformats-officedocument.spreadsheetml.sheet"
    );
    assert.ok(appended, "Anchor must be appended to document.body");
    assert.ok(clicked, "Anchor must be clicked");
    assert.ok(removed, "Anchor must be removed");
    assert.equal(
      revokedUrl,
      "blob:mock-application/vnd.openxmlformats-officedocument.spreadsheetml.sheet"
    );
  } finally {
    globalThis.window = originalWindow;
    globalThis.document = originalDocument;
    globalThis.Blob = originalBlob;
    globalThis.URL = originalUrl;
  }
});

// --- mapSupabaseUser Tests ---

test("mapSupabaseUser returns null when passed null or undefined", () => {
  assert.equal(mapSupabaseUser(null), null);
  assert.equal(mapSupabaseUser(undefined), null);
});

test("mapSupabaseUser maps valid admin user correctly", () => {
  const mapped = mapSupabaseUser({
    id: "user-admin-1",
    email: "admin@llumitaula.com",
    app_metadata: { role: "admin" },
  });

  assert.deepEqual(mapped, {
    id: "user-admin-1",
    name: "admin",
    email: "admin@llumitaula.com",
    role: "admin",
  });
});

test("mapSupabaseUser maps supervisor and monitor roles correctly", () => {
  const supervisor = mapSupabaseUser({
    id: "user-sup-1",
    email: "supervisor.maria@colegio.es",
    app_metadata: { role: "supervisor" },
  });
  assert.equal(supervisor?.role, "supervisor");
  assert.equal(supervisor?.name, "supervisor.maria");

  const monitor = mapSupabaseUser({
    id: "user-mon-1",
    email: "monitor.juan@colegio.es",
    app_metadata: { role: "monitor" },
  });
  assert.equal(monitor?.role, "monitor");
  assert.equal(monitor?.name, "monitor.juan");
});

test("mapSupabaseUser defaults to 'monitor' for unknown or missing role", () => {
  const unknownRole = mapSupabaseUser({
    id: "user-unk-1",
    email: "unknown@example.com",
    app_metadata: { role: "superadmin" },
  });
  assert.equal(unknownRole?.role, "monitor");

  const missingAppMeta = mapSupabaseUser({
    id: "user-nometa-1",
    email: "nometa@example.com",
  });
  assert.equal(missingAppMeta?.role, "monitor");

  const nullRole = mapSupabaseUser({
    id: "user-nullrole-1",
    email: "nullrole@example.com",
    app_metadata: { role: null },
  });
  assert.equal(nullRole?.role, "monitor");
});

test("mapSupabaseUser handles missing or empty email gracefully", () => {
  const noEmail = mapSupabaseUser({
    id: "user-noemail-1",
  });
  assert.deepEqual(noEmail, {
    id: "user-noemail-1",
    name: "User",
    email: "",
    role: "monitor",
  });

  const emptyEmail = mapSupabaseUser({
    id: "user-emptyemail-1",
    email: "",
  });
  assert.deepEqual(emptyEmail, {
    id: "user-emptyemail-1",
    name: "User",
    email: "",
    role: "monitor",
  });
});
