test("mapSupabaseUser returns null when passed null or undefined", () => {
  assert.equal(mapSupabaseUser(null), null);
  assert.equal(mapSupabaseUser(undefined), null);
});

test("mapSupabaseUser maps valid admin user correctly", () => {
  const mapped = mapSupabaseUser({
    id: "user-admin-1",
    email: "admin@llumitaula.com",
    app_metadata: { role: "admin" },
  });

  assert.deepEqual(mapped, {
    id: "user-admin-1",
    name: "admin",
    email: "admin@llumitaula.com",
    role: "admin",
  });
});

test("mapSupabaseUser maps supervisor and monitor roles correctly", () => {
  const supervisor = mapSupabaseUser({
    id: "user-sup-1",
    email: "supervisor.maria@colegio.es",
    app_metadata: { role: "supervisor" },
  });
  assert.equal(supervisor?.role, "supervisor");
  assert.equal(supervisor?.name, "supervisor.maria");

  const monitor = mapSupabaseUser({
    id: "user-mon-1",
    email: "monitor.juan@colegio.es",
    app_metadata: { role: "monitor" },
  });
  assert.equal(monitor?.role, "monitor");
  assert.equal(monitor?.name, "monitor.juan");
});

test("mapSupabaseUser defaults to 'monitor' for unknown or missing role", () => {
  const unknownRole = mapSupabaseUser({
    id: "user-unk-1",
    email: "unknown@example.com",
    app_metadata: { role: "superadmin" },
  });
  assert.equal(unknownRole?.role, "monitor");

  const missingAppMeta = mapSupabaseUser({
    id: "user-nometa-1",
    email: "nometa@example.com",
  });
  assert.equal(missingAppMeta?.role, "monitor");

  const nullRole = mapSupabaseUser({
    id: "user-nullrole-1",
    email: "nullrole@example.com",
    app_metadata: { role: null },
  });
  assert.equal(nullRole?.role, "monitor");
});

test("mapSupabaseUser handles missing or empty email gracefully", () => {
  const noEmail = mapSupabaseUser({
    id: "user-noemail-1",
  });
  assert.deepEqual(noEmail, {
    id: "user-noemail-1",
    name: "User",
    email: "",
    role: "monitor",
  });

  const emptyEmail = mapSupabaseUser({
    id: "user-emptyemail-1",
    email: "",
  });
  assert.deepEqual(emptyEmail, {
    id: "user-emptyemail-1",
    name: "User",
    email: "",
    role: "monitor",
  });
});
